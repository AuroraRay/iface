// EXPORTS: ISkincareProduct, IUsageLog, MOCK_PRODUCTS, MOCK_USAGE_LOGS
export interface ISkincareProduct {
  id: string
  name: string
  brand?: string
  category:
    | 'cleanser'
    | 'toner'
    | 'serum'
    | 'cream'
    | 'sunscreen'
    | 'mask'
    | 'makeup'
    | 'lip_care'
    | 'hair_care'
    | 'hair_body'
    | 'perfume'
    | 'body_care'
    | 'skincare_tool'
    | 'other'
  volume: string
  /** 总容量数值（ml 或 g），用于单价计算；片/颗/套装等为 0 */
  totalVolumeMl: number
  /** 容量单位 */
  volumeUnit: 'ml' | 'g' | 'pcs' | 'set'
  /** 购买数量（件数） */
  purchaseCount: number
  /** 剩余百分比 0-100 */
  quantity: number
  /** 实付金额（元），赠品为标注价值 */
  purchasePrice: number
  /** 每 ml 或每 g 单价（元），无容量单位时为 0 */
  unitPrice: number
  /** 购买日期 */
  purchaseDate: string
  /** 开封日期 */
  openDate: string
  /** 保质期到期日 */
  expiryDate: string
  /** 用途描述 */
  purpose?: string
  /** 功效标签（可多选叠加，如抗老 + 美白） */
  efficacies?: string[]
  /** 主要成分（标准名，可多个，如视黄醇、玻色因） */
  ingredients?: string[]
  note?: string
  /** 是否为赠品/中样 */
  isGift: boolean
  /** 是否已开封 */
  isOpened: boolean
  /** 是否已暂停使用（开封后停用） */
  isPaused: boolean
  status:
    | 'unopened_sealed'   // 未开封全新
    | 'opened_unused'     // 已开封未使用
    | 'opened_in_use'     // 已开封使用中
    | 'opened_paused'     // 已开封暂停使用
    | 'used_up'           // 已用完
    | 'expired'           // 已过期
  source: 'mock' | 'user'
}

export interface IUsageLog {
  id: string
  productId: string
  amount: number
  usedAt: string
  note?: string
}

